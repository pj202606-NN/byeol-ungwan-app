// ── 별운관 고정 양력 생일로 본명수 찾기 ──────────────────────────
// month/day는 숫자이며, year는 유효한 실제 날짜 확인용 선택 인수입니다.
// year 생략 시 2/29도 판정할 수 있도록 윤년(2000년)을 기준으로 검증합니다.
export function getMansionByDate(month, day, year = 2000) {
  if (![year, month, day].every(Number.isInteger) || year < 1 || year > 9999 || month < 1 || month > 12 || day < 1) return null;
  const leap = year % 4 === 0 && (year % 100 !== 0 || year % 400 === 0);
  const monthDays = [31, leap ? 29 : 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31];
  if (day > monthDays[month - 1]) return null;
  const dateNumber = month * 100 + day;
  const found = MANSIONS.filter(({ 날짜시작: start, 날짜종료: end }) => {
    const a = start.월 * 100 + start.일;
    const b = end.월 * 100 + end.일;
    return a <= b ? (a <= dateNumber && dateNumber <= b) : (dateNumber >= a || dateNumber <= b);
  });
  if (found.length !== 1) throw new Error(`별자리 날짜 범위 중복/누락: ${month}/${day} → ${found.length}건`);
  return found[0];
}

